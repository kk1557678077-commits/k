    if age < 0:
        return
    pop = back_out(age / 0.25)
    w = text_w(s, size) / 2 + 26
    c.shape([(x + tail[0] * 0.35, y + 20 * pop), (x + tail[0] * pop, y + tail[1] * pop), (x + 8, y + 22 * pop)],
            fill=WHITE, lw=3.2, wob=0.6)
    c.shape(ell(x, y, w * pop, 36 * pop, 30), fill=WHITE, lw=3.4, wob=0.8)
    c.text(s, x, y, size * pop, colors=color, outline=INK, sw=2.5)


