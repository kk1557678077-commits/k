def mud_drops(c, t, period, life, origin, seed, vx=-260.0):
    k0 = int(math.floor((t - life) / period)) + 1
    for k in range(k0, int(math.floor(t / period)) + 1):
        ts = k * period
        age = t - ts
        if age < 0 or age > life:
            continue
        o = origin(ts)
        if o is None:
            continue
        vx_ = vx * (0.6 + 0.7 * hash01(k, seed))
        vy = -330 - 160 * hash01(k, seed + 1)
        x = o[0] + vx_ * age
        y = o[1] + vy * age + 900 * age * age
        r = 5 + 4 * hash01(k, seed + 2)
        c.shape(ell(x, y, r, r * 0.85, 12), fill=MUD, line=DMUD, lw=2.0, wob=0.4)


