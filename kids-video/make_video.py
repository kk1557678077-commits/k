# ---------------------------------------------------------------- small maths
def clamp(v, a=0.0, b=1.0):
    return max(a, min(b, v))


def ease_out(p):
    p = clamp(p)
    return 1 - (1 - p) ** 3


def ease_in_out(p):
    p = clamp(p)
    return p * p * (3 - 2 * p)


def back_out(p):
    """Pop-in with a little overshoot."""
    p = clamp(p)
    k = 2.2
    return 1 + (k + 1) * (p - 1) ** 3 + k * (p - 1) ** 2


def hash01(i, seed=0):
    v = math.sin(i * 12.9898 + seed * 78.233) * 43758.5453
    return v - math.floor(v)


# ---------------------------------------------------------------- textures
PAD = 192


def _directional_blur(a, ang, length):
    rad = math.radians(ang)
    dx, dy = math.cos(rad), math.sin(rad)
    acc = np.zeros_like(a)
    for k in range(-length, length + 1):
        acc += np.roll(a, (int(round(k * dy)), int(round(k * dx))), axis=(0, 1))
    return acc / (2 * length + 1)


TEX_SPECS = [  # (stroke angle, streak strength, coverage, stroke length)
    (32, 0.20, 0.88, 18), (-34, 0.20, 0.88, 18), (60, 0.20, 0.88, 18), (-58, 0.20, 0.88, 18),  # objects
    (-7, 0.15, 0.86, 26),   # SKY_TEX: back-and-forth colouring of a big area
    (-4, 0.07, 0.95, 26),   # SOFT_TEX: road / night sky, pressed hard
    (-12, 0.18, 0.88, 14),  # GRASS_TEX
]
SKY_TEX, SOFT_TEX, GRASS_TEX = 4, 5, 6
# Big background areas keep the same crayon grain from frame to frame (calmer to watch and far
# cheaper to encode); everything else gets re-scribbled with each new drawing.
STATIC_TEX = (SKY_TEX, SOFT_TEX, GRASS_TEX)


def _make_textures():
    """Crayon fill textures (streaky, with paper tooth) plus a grainy stroke texture."""
    rng = np.random.default_rng(20261015)
    th, tw = H + PAD, W + PAD
    tex = []
    for ang, strength, cover, length in TEX_SPECS:
        coarse = rng.random((th // 3 + 2, tw // 3 + 2)).astype(np.float32)
        n = np.asarray(Image.fromarray(coarse).resize((tw, th), Image.BILINEAR))
        s = _directional_blur(n, ang, int(length * S))
        s = (s - s.mean()) / (s.std() + 1e-6)
        streak = np.clip(cover + strength * s, 0.0, 1.0)
        speck = np.kron(rng.random((th // 2 + 1, tw // 2 + 1)), np.ones((2, 2)))[:th, :tw]
        tooth = np.where(speck > 0.91, 0.65, 1.0)
        tex.append((streak * tooth).astype(np.float32))
    tooth = np.where(rng.random((th, tw)) > 0.82, 0.55, 1.0)
    tex.append(tooth.astype(np.float32))
    return tex


def _make_paper():
    rng = np.random.default_rng(7)
    base = np.array([251, 247, 236], np.float32)
    low = rng.random((H // 40 + 2, W // 40 + 2)).astype(np.float32)
    low = np.asarray(Image.fromarray(low).resize((W, H), Image.BICUBIC))
    fine = rng.random((H, W)).astype(np.float32)
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    vig = (xx / W - 0.5) ** 2 + (yy / H - 0.5) ** 2
    shade = (low - 0.5) * 7 + (fine - 0.5) * 8 - vig * 26
    return np.clip(base[None, None, :] + shade[..., None], 0, 255).astype(np.float32)


TEX = _make_textures()
STROKE_TEX = len(TEX) - 1
PAPER = _make_paper()


# ---------------------------------------------------------------- geometry
def ell(cx, cy, rx, ry, n=32, a0=0.0):
    a = np.linspace(0, 2 * np.pi, n, endpoint=False) + a0
    return np.stack([cx + rx * np.cos(a), cy + ry * np.sin(a)], 1)


def rect(x0, y0, x1, y1):
    return np.array([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], np.float64)


def rrect(x0, y0, x1, y1, r):
    pts = []
    for cx, cy, a0 in ((x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)):
        for a in np.linspace(a0, a0 + 90, 6):
            pts.append((cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))))
    return np.array(pts)


def star(cx, cy, r, n=5, inner=0.45, rot=-90.0):
    pts = []
    for k in range(2 * n):
        rr = r if k % 2 == 0 else r * inner
        a = math.radians(rot + k * 180.0 / n)
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return np.array(pts)


def heart(cx, cy, size):
    t = np.linspace(0, 2 * np.pi, 36, endpoint=False)
    x = 16 * np.sin(t) ** 3
    y = -(13 * np.cos(t) - 5 * np.cos(2 * t) - 2 * np.cos(3 * t) - np.cos(4 * t))
    return np.stack([cx + x * size / 16, cy + y * size / 16], 1)


def tear(cx, cy, r):
    arc = [(cx + r * math.cos(a), cy + r * math.sin(a)) for a in np.linspace(-0.35, math.pi + 0.35, 12)]
    return np.array([(cx, cy - 2.2 * r)] + arc)


def scallop(cx, cy, rx, ry, bumps=7, n=70, rot=0.0):
    """Puffy cloud / bush outline."""
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    k = 0.82 + 0.22 * np.abs(np.sin(a * bumps / 2 + rot))
    return np.stack([cx + rx * k * np.cos(a), cy + ry * k * np.sin(a)], 1)


def xf(pts, x, y, s=1.0, rot=0.0, flip=False):
    """Rotate (degrees, clockwise on screen), scale, then move local points."""
    p = np.asarray(pts, np.float64).reshape(-1, 2).copy()
    if flip:
        p[:, 0] = -p[:, 0]
    if rot:
        c, sn = math.cos(math.radians(rot)), math.sin(math.radians(rot))
        p = np.stack([p[:, 0] * c - p[:, 1] * sn, p[:, 0] * sn + p[:, 1] * c], 1)
    return p * s + np.array([x, y])


def wobble(pts, seed, amp, closed=True, step=8.0, overshoot=False):
    """Resample a path and push it around with smooth noise: the hand-drawn line."""
    pts = np.asarray(pts, np.float64)
    if len(pts) < 2:
        return pts
    P = np.vstack([pts, pts[:1]]) if closed else pts
    seg = np.hypot(np.diff(P[:, 0]), np.diff(P[:, 1]))
    cum = np.concatenate([[0.0], np.cumsum(seg)])
    total = cum[-1]
    if total < 1e-6:
        return pts
    n = max(int(total / step), 4)
    t = np.unique(np.concatenate([np.linspace(0, total, n + 1), cum]))
    if closed and overshoot:  # the crayon doesn't quite stop where it started
        t = np.concatenate([t, total + np.linspace(1.0, min(total * 0.07, 20.0), 3)])
    tm = np.mod(t, total) if closed else t
    x = np.interp(tm, cum, P[:, 0])
    y = np.interp(tm, cum, P[:, 1])
    if amp > 0:
        r = np.random.default_rng(seed)
        ph = r.uniform(0, 2 * np.pi, 4)
        fq = r.uniform(0.7, 1.3, 4)
        x = x + amp * (0.65 * np.sin(t * fq[0] / 38 + ph[0]) + 0.35 * np.sin(t * fq[1] / 11 + ph[1]))
        y = y + amp * (0.65 * np.sin(t * fq[2] / 38 + ph[2]) + 0.35 * np.sin(t * fq[3] / 11 + ph[3]))
    return np.stack([x, y], 1)


# ---------------------------------------------------------------- lettering
@functools.lru_cache(maxsize=None)
def _font(px):
    return ImageFont.truetype(FONT, px)


@functools.lru_cache(maxsize=8000)
def _glyph(ch, px, sw, ang):
    f = _font(px)
    c = int(px * 1.8) + 2 * sw + 4
    outer = Image.new("L", (c, c), 0)
    ImageDraw.Draw(outer).text((c / 2, c / 2), ch, font=f, fill=255, anchor="mm",
                               stroke_width=sw, stroke_fill=255)
    inner = Image.new("L", (c, c), 0)
    ImageDraw.Draw(inner).text((c / 2, c / 2), ch, font=f, fill=255, anchor="mm")
    if ang:
        outer = outer.rotate(ang, resample=Image.BICUBIC)
        inner = inner.rotate(ang, resample=Image.BICUBIC)
    return np.asarray(outer), np.asarray(inner)


def text_w(s, size, spacing=0.06):
    f = _font(max(4, int(size * S)))
    return sum(f.getlength(ch) for ch in s) / S * (1 + spacing)


# ---------------------------------------------------------------- the paper
class Canvas:
    def __init__(self, frame):
        self.frame = frame
        self.boil = frame // BOIL
        self.img = PAPER.copy()
        r = np.random.default_rng(self.boil * 7907 + 13)
        self.offs = [(int(r.integers(0, PAD)), int(r.integers(0, PAD))) for _ in TEX]
        for i in STATIC_TEX:
            self.offs[i] = (PAD // 2, PAD // 2)
        self.n = 0

    def seed(self):
        self.n += 1
        return (self.boil * 1000003 + self.n * 7919) % (2 ** 31)

    # -- low level: blend a coverage mask (pixel space) in a crayon colour
    def _apply(self, mask, x0, y0, color, tex, alpha):
        h, w = mask.shape
        X0, Y0 = max(x0, 0), max(y0, 0)
        X1, Y1 = min(x0 + w, W), min(y0 + h, H)
        if X1 <= X0 or Y1 <= Y0 or alpha <= 0.003:
            return
        m = mask[Y0 - y0:Y1 - y0, X0 - x0:X1 - x0].astype(np.float32) * (alpha / 255.0)
        if tex is not None:
            ox, oy = self.offs[tex]
            m *= TEX[tex][oy + Y0:oy + Y1, ox + X0:ox + X1]
        reg = self.img[Y0:Y1, X0:X1]
        reg += (np.asarray(color, np.float32) - reg) * m[..., None]

    @staticmethod
    def _scratch(pts, pad):
        x0 = int(math.floor(pts[:, 0].min() - pad))
        y0 = int(math.floor(pts[:, 1].min() - pad))
        x1 = int(math.ceil(pts[:, 0].max() + pad))
        y1 = int(math.ceil(pts[:, 1].max() + pad))
        x0, y0, x1, y1 = max(x0, 0), max(y0, 0), min(x1, W), min(y1, H)
        if x1 <= x0 or y1 <= y0:
            return None
        return Image.new("L", (x1 - x0, y1 - y0), 0), x0, y0

    def fill_px(self, pts, color, tex, alpha):
        sc = self._scratch(pts, 2)
        if sc is None:
            return
        im, x0, y0 = sc
        ImageDraw.Draw(im).polygon([(x - x0, y - y0) for x, y in pts], fill=255)
        self._apply(np.asarray(im), x0, y0, color, tex, alpha)

    def line_px(self, pts, color, width, alpha):
        sc = self._scratch(pts, width + 2)
        if sc is None:
            return
        im, x0, y0 = sc
        d = ImageDraw.Draw(im)
        p = [(x - x0, y - y0) for x, y in pts]
        wi = max(1, int(round(width)))
        d.line(p, fill=255, width=wi, joint="curve")
        r = wi / 2.0
        for x, y in (p[0], p[-1]):
            d.ellipse([x - r, y - r, x + r, y + r], fill=255)
        self._apply(np.asarray(im), x0, y0, color, STROKE_TEX, alpha)

    # -- high level, in design units
    def shape(self, pts, fill=None, line=INK, lw=4.0, wob=1.6, alpha=1.0, tex=None,
              closed=True, fill_alpha=1.0):
        pts = np.asarray(pts, np.float64)
        if fill is not None:
            fp = wobble(pts, self.seed(), wob * 1.3, closed=True)
            t = (self.n % 4) if tex is None else tex
            self.fill_px(fp * S, fill, t, alpha * fill_alpha)
        if line is not None:
            lp = wobble(pts, self.seed(), wob, closed=closed, overshoot=closed)
            self.line_px(lp * S, line, lw * S, alpha)

    def line(self, pts, color=INK, lw=4.0, wob=1.4, alpha=1.0):
        self.shape(pts, fill=None, line=color, lw=lw, wob=wob, alpha=alpha, closed=False)

    def dot(self, x, y, r, color=INK, alpha=1.0):
        self.shape(ell(x, y, r, r, 12), fill=color, line=None, wob=0.3, alpha=alpha, tex=STROKE_TEX)

    def text(self, s, cx, cy, size, colors=RAINBOW, outline=INK, sw=None, scales=None,
             wave=0.0, t=0.0, tilt=5.0, alpha=1.0, spacing=0.06):
        """Hand-lettered text centred on (cx, cy): every letter a little crooked."""
        f = _font(max(4, int(size * S)))
        advs = [f.getlength(ch) / S * (1 + spacing) for ch in s]
        x = cx - sum(advs) / 2
        r = np.random.default_rng((self.boil * 31 + len(s) * 7 + int(cx)) % (2 ** 31))
        for i, ch in enumerate(s):
            ang = int(round(r.uniform(-tilt, tilt)))
            dy = r.uniform(-2.0, 2.0) + wave * math.sin(t * 4 + i * 0.7)
            ccx = x + advs[i] / 2
            x += advs[i]
            sc = 1.0 if scales is None else scales[i]
            if sc <= 0.03 or ch == " ":
                continue
            px = max(4, int(size * sc * S))
            swp = max(1, int(round((sw if sw is not None else size * 0.09) * sc * S)))
            outer, inner = _glyph(ch, px, swp, ang)
            col = colors[i % len(colors)] if isinstance(colors, list) else colors
            c = outer.shape[0]
            gx = int(round(ccx * S - c / 2))
            gy = int(round((cy + dy) * S - c / 2))
            if outline is not None:
                self._apply(outer, gx, gy, outline, STROKE_TEX, alpha)
            self._apply(inner, gx, gy, col, 0, alpha)


