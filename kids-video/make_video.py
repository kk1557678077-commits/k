def firework(c, x, y, age, color):
    if age < -0.45 or age > 1.35:
        return
    if age < 0:  # rocket on its way up
        p = (age + 0.45) / 0.45
        ry = y + (1 - p) * 330
        c.line([(x, ry + 46), (x, ry + 6)], color=ORANGE, lw=3.4, wob=0.6)
        sparkle(c, x, ry, 8, color=YELLOW)
        return
    p = ease_out(age / 0.85)
    r = 112 * p
    alpha = 1 - clamp((age - 0.75) / 0.6)
    for j in range(14):
        a = 2 * math.pi * j / 14 + 0.2
        r0 = r * 0.5
        drop = 22 * age * age
        c.line([(x + r0 * math.cos(a), y + r0 * math.sin(a) + drop * 0.5),
                (x + r * math.cos(a), y + r * math.sin(a) + drop)], color=color, lw=4.4, alpha=alpha, wob=0.8)
        c.dot(x + (r + 9) * math.cos(a), y + (r + 9) * math.sin(a) + drop, 3.5, color=YELLOW, alpha=alpha)
    if age < 0.18:
        sparkle(c, x, y, 26, color=WHITE, alpha=1 - age / 0.18)


