def checker_strip(c, x, y0, y1, sq=22):
    c.shape(rect(x - sq, y0, x + sq, y1), fill=WHITE, line=INK, lw=3.2, wob=0.8)
    n = int((y1 - y0) // sq)
    for r_ in range(n):
        for col in range(2):
            if (r_ + col) % 2 == 0:
                xx = x - sq + col * sq
                yy = y0 + r_ * sq
                c.shape(rect(xx, yy, xx + sq, min(yy + sq, y1)), fill=INK, line=None, wob=0.4, tex=STROKE_TEX)


