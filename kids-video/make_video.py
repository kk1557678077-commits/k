def _body_with_arches(upper, wheels_x):
    pts = list(upper)  # rear-bottom corner, over the roof, to front-bottom corner
    for wx in sorted(wheels_x, reverse=True):  # then back along the sill: front arch first
        for a in np.linspace(-0.35, math.pi + 0.35, 14):
            pts.append((wx + ARCH_R * math.cos(a), WHEEL_Y - ARCH_R * math.sin(a)))
    return np.array(pts)


