def car_frame(x, y, s, tilt, bob):
    """Local car coords -> screen. The body pivots on the axle line and bounces on its springs."""
    def B(p):
        p = np.asarray(p, np.float64).reshape(-1, 2) - np.array([0.0, WHEEL_Y])
        p = xf(p, 0.0, WHEEL_Y, 1.0, -tilt)
        return xf(p, x, y - bob * s, s)
    return B


