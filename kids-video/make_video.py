XFADE = 0.25


def _draw(frame, t, fn):
    c = Canvas(frame)
    fn(c, t)
    return c.img


def render(frame):
    t = frame / FPS
    idx = len(SCENES) - 1
    for i, (a, b, _) in enumerate(SCENES):
        if a <= t < b:
            idx = i
            break
    img = _draw(frame, t, SCENES[idx][2])
    for i in range(len(SCENES) - 1):  # short cross-dissolves between scenes
        T = SCENES[i][1]
        if abs(t - T) <= XFADE / 2:
            w = (t - (T - XFADE / 2)) / XFADE
            if t < T:
                img = img * (1 - w) + _draw(frame, t, SCENES[i + 1][2]) * w
            else:
                img = _draw(frame, t, SCENES[i][2]) * (1 - w) + img * w
    return np.clip(img, 0, 255).astype(np.uint8)


def render_bytes(frame):
    return render(frame).tobytes()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--still", type=float, nargs="*", help="render frames at these times (s) as PNGs")
    ap.add_argument("--outdir", default=".", help="where --still PNGs go")
    ap.add_argument("--audio", help="use this WAV instead of synthesising soundtrack.py")
    ap.add_argument("--out", default=OUT_MP4)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 2)
    ap.add_argument("--crf", type=int, default=27, help="x264 quality (lower = bigger, sharper)")
    args = ap.parse_args()

    if args.still:
        for ts in args.still:
            fr = int(round(ts * FPS))
            p = os.path.join(args.outdir, f"still_{ts:05.2f}.png")
            Image.fromarray(render(fr)).save(p)
            print(p)
        return

    with tempfile.TemporaryDirectory() as tmp:
        audio = args.audio
        if not audio:
            audio = os.path.join(tmp, "soundtrack.wav")
            soundtrack.write_wav(audio, soundtrack.build())
        n = int(round(FPS * DURATION))
        cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
               "-r", str(FPS), "-i", "-", "-i", audio, "-c:v", "libx264", "-preset", "slow", "-tune", "animation", "-crf", str(args.crf),
               "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k", "-shortest", "-movflags", "+faststart",
               args.out]
        enc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
        with Pool(args.jobs) as pool:
            for i, buf in enumerate(pool.imap(render_bytes, range(n), chunksize=4)):
                enc.stdin.write(buf)
                if i % 48 == 0:
                    print(f"frame {i}/{n}", flush=True)
        enc.stdin.close()
        if enc.wait() != 0:
            sys.exit("ffmpeg failed")
    print(args.out)


if __name__ == "__main__":
    main()
